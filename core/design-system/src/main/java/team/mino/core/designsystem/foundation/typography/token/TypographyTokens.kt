private fun minoTextStyle(
    weight: FontWeight,
    size: TextUnit,
    lineHeight: TextUnit,
    letterSpacing: TextUnit,
): TextStyle =
    TextStyle(
        fontFamily = AtomicTypographyToken.FontFamilySuite,
        fontWeight = weight,
        fontSize = size,
        lineHeight = lineHeight,
        letterSpacing = letterSpacing,
    )
